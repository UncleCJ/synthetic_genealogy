"""
Research log: check entries, write the index, create entries, look up
entries by chromosome position. Format: research/README.md.
"""
import datetime as dt
import re
import sys
import tomllib
from pathlib import Path

def _research_dir():
    """Entries live with the other hand-kept notes, data/notes/research/
    (private, see docs/data.md); research/ in the repo keeps README.md (the
    format) and is the fallback for a data folder not yet sorted."""
    try:
        import config
        d = Path(config.load()["data_dir"]) / "notes" / "research"
        if d.is_dir():
            return d
    except SystemExit:
        pass
    d = Path(__file__).parent / "research"
    print(f"research_log: no notes/research/ in the data folder; using {d}"
          " (git-ignored but for README.md)", file=sys.stderr)
    return d


DIR = _research_dir()
KINDS = {
    "question": ("open", "parked", "answered"),
    "hypothesis": ("open", "supported", "refuted", "parked"),
    "segment": ("open", "explained", "parked"),
    "finding": ("settled", "retracted"),
    "note": ("open", "done"),
}
PREFIX = {"question": "q", "hypothesis": "h", "segment": "s", "finding": "f", "note": "n"}
REQUIRED = ("id", "kind", "title", "status", "created")
SKIP = {"README.md", "INDEX.md"}


def read(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"\+\+\+\n(.*?)\n\+\+\+\n?(.*)", text, re.S)
    if not m:
        raise ValueError("missing +++ TOML header")
    return tomllib.loads(m.group(1)), m.group(2)


def entries():
    out, problems = {}, []
    for p in sorted(DIR.glob("*.md")):
        if p.name in SKIP:
            continue
        try:
            h, body = read(p)
        except Exception as e:                     # noqa: BLE001 - report and go on
            problems.append(f"{p.name}: {e}")
            continue
        for k in REQUIRED:
            if k not in h:
                problems.append(f"{p.name}: missing {k}")
        if h.get("id") != p.stem:
            problems.append(f"{p.name}: id {h.get('id')!r} != file name")
        kind = h.get("kind")
        if kind not in KINDS:
            problems.append(f"{p.name}: unknown kind {kind!r}")
        elif h.get("status") not in KINDS[kind]:
            problems.append(f"{p.name}: status {h.get('status')!r} not in {KINDS[kind]}")
        h["_body"] = body
        out[p.stem] = h
    for i, h in out.items():
        for r in h.get("related", []):
            if r not in out:
                problems.append(f"{i}.md: related {r!r} does not exist")
    return out, problems


def _summary(body):
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return line[:140]
    return ""


def write_index(es):
    order = ["question", "hypothesis", "segment", "finding", "note"]
    active = {"open", "parked"}
    lines = ["# Research log index", "",
             "Generated by `research_log.py`; edit the entries, not this file.", ""]
    for title, pick in (("Active", lambda h: h["status"] in active),
                        ("Settled", lambda h: h["status"] not in active)):
        lines += [f"## {title}", ""]
        for kind in order:
            hs = sorted((h for h in es.values() if h["kind"] == kind and pick(h)),
                        key=lambda h: str(h.get("updated", h["created"])), reverse=True)
            if not hs:
                continue
            plural = {"hypothesis": "Hypotheses"}.get(kind, kind.capitalize() + "s")
            lines += [f"### {plural}", "",
                      "| entry | status | updated | lineage | summary |", "|---|---|---|---|---|"]
            for h in hs:
                lines.append(f"| [{h['title']}]({h['id']}.md) | {h['status']} | "
                             f"{h.get('updated', h['created'])} | {' '.join(h.get('lineage', []))} | "
                             f"{_summary(h['_body']).replace('|', '/')} |")
            lines.append("")
    (DIR / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")


def new(kind, title):
    if kind not in KINDS:
        raise SystemExit(f"kind must be one of {', '.join(KINDS)}")
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40]
    i = f"{PREFIX[kind]}-{slug}"
    p = DIR / f"{i}.md"
    if p.exists():
        raise SystemExit(f"{p} exists")
    today = dt.date.today().isoformat()
    p.write_text(f'''+++
id = "{i}"
kind = "{kind}"
title = "{title}"
status = "{KINDS[kind][0]}"
created = {today}
updated = {today}
people = []
lineage = []
related = []
evidence = []
segments = []
+++

## Context

## Evidence

## Next

## Log

- {today}: created.
''', encoding="utf-8")
    print(p)


def at(chrom, pos):
    es, _ = entries()
    for h in es.values():
        for s in h.get("segments", []):
            if str(s.get("chrom")) == str(chrom) and s.get("start", 0) <= pos <= s.get("end", 0):
                print(f"{h['id']} [{h['status']}] {s.get('subject', '')} "
                      f"chr{chrom}:{s['start']/1e6:.1f}-{s['end']/1e6:.1f} Mb {s.get('match', '')}")


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["new"] and len(a) == 3:
        new(a[1], a[2])
    elif a[:1] == ["at"] and len(a) == 3:
        at(a[1], float(a[2]))
    elif not a:
        es, problems = entries()
        write_index(es)
        print(f"{len(es)} entries -> {DIR / 'INDEX.md'}")
        for p in problems:
            print("problem:", p)
        sys.exit(1 if problems else 0)
    else:
        raise SystemExit(__doc__ + "\nusage: research_log.py [new <kind> <title> | at <chrom> <bp>]")
